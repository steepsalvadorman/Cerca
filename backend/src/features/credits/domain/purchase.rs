use chrono::{DateTime, Utc};
use uuid::Uuid;

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum PurchaseStatus {
    Pending,
    Paid,
    Failed,
}

impl PurchaseStatus {
    pub fn as_str(&self) -> &'static str {
        match self {
            PurchaseStatus::Pending => "pending",
            PurchaseStatus::Paid => "paid",
            PurchaseStatus::Failed => "failed",
        }
    }

    pub fn parse(raw: &str) -> Self {
        match raw {
            "paid" => PurchaseStatus::Paid,
            "failed" => PurchaseStatus::Failed,
            _ => PurchaseStatus::Pending,
        }
    }
}

/// One attempt to buy a pack. `id` is generated by the app and is the
/// idempotency key: a retried request finds this row instead of charging
/// the card a second time.
#[derive(Debug, Clone)]
pub struct CreditPurchase {
    pub id: Uuid,
    pub technician_profile_id: i32,
    pub pack_id: String,
    pub credits: i32,
    pub amount_cents: i32,
    pub status: PurchaseStatus,
    pub gateway: Option<String>,
    pub gateway_reference: Option<String>,
    pub failure_message: Option<String>,
    pub simulated: bool,
    pub created_at: DateTime<Utc>,
}
